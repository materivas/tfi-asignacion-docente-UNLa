CREATE TABLE IF NOT EXISTS revision_info (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_timestamp bigint NOT NULL,
    modified_by varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS asignacion_aud (
    id bigint NOT NULL,
    rev integer NOT NULL REFERENCES revision_info(id),
    revtype smallint,
    materia_id bigint,
    cuatrimestre_id bigint,
    turno varchar(255),
    anio integer,
    dia varchar(255),
    comision varchar(50),
    created_by varchar(100),
    updated_by varchar(100),
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    PRIMARY KEY (id, rev)
);

CREATE TABLE IF NOT EXISTS docente_aud (
    id bigint NOT NULL,
    rev integer NOT NULL REFERENCES revision_info(id),
    revtype smallint,
    nombre varchar(255),
    dni varchar(255),
    email varchar(255),
    categoria_id bigint,
    dedicacion varchar(255),
    concursado boolean,
    usuario_id bigint,
    created_by varchar(100),
    updated_by varchar(100),
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    PRIMARY KEY (id, rev)
);

CREATE TABLE IF NOT EXISTS materia_aud (
    id bigint NOT NULL,
    rev integer NOT NULL REFERENCES revision_info(id),
    revtype smallint,
    nombre varchar(255),
    plan_id bigint,
    anio integer,
    codigo integer,
    created_by varchar(100),
    updated_by varchar(100),
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    PRIMARY KEY (id, rev)
);

CREATE TABLE IF NOT EXISTS asignacion_docente_aud (
    id bigint NOT NULL,
