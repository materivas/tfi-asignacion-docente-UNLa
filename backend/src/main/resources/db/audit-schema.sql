    revtype smallint,
    asignacion_id bigint,
    docente_id bigint,
    rol_id bigint,
    horas_asignadas integer,
    confirmado boolean,
    created_by varchar(100),
    updated_by varchar(100),
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    PRIMARY KEY (id, rev)
);
